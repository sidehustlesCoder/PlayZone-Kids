// Helper functions
export function getGamesByCategory(category) {
  if (category === 'all') return GAMES.filter(g => g.status === 'live')
  return GAMES.filter(g => g.status === 'live' && (g.category === category || g.tags.includes(category)))
}

export function getLiveGames() {
  return GAMES.filter(g => g.status === 'live')
}

export function getComingSoonGames() {
  return GAMES.filter(g => g.status === 'coming-soon')
}

export function getFeaturedGames() {
  return GAMES.filter(g => g.isFeatured)
}

export function getNewGames() {
  return GAMES.filter(g => g.isNew)
}

export function getTrendingGames() {
  return [...GAMES].filter(g => g.status === 'live').sort((a, b) => b.playCount - a.playCount).slice(0, 8)
}

export function searchGames(query) {
  const q = query.toLowerCase()
  return GAMES.filter(g =>
    g.name.toLowerCase().includes(q) ||
    g.description.toLowerCase().includes(q) ||
    g.tags.some(t => t.includes(q))
  )
}

export function getGameById(id) {
  return GAMES.find(g => g.id === id)
}

export function getDailyGame() {
  const liveGames = getLiveGames()
  if (!liveGames.length) return null
  const today = new Date().toISOString().slice(0, 10)
  let hash = 0
  for (let i = 0; i < today.length; i++) {
    hash = (hash << 5) - hash + today.charCodeAt(i)
    hash |= 0
  }
  return liveGames[Math.abs(hash) % liveGames.length]
}
